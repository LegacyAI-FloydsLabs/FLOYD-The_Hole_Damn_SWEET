/** The bearer token a terminal's hook posts must carry: HMAC-SHA256 of the
 *  terminal id under the per-boot secret. Binding the token to the terminal id
 *  means a process can only post events for ITS OWN terminal — reading the
 *  env of one PTY yields nothing that spoofs another. */
export function hookTokenForTerminal(secret, terminalId) {
  return createHmac('sha256', secret).update(terminalId).digest('hex');
}

/** Constant-time check of the presented bearer against the terminal's derived
 *  token. Length equality first (timingSafeEqual throws on mismatched lengths;
 *  the expected length is public anyway). */
export function hookTokenMatches(authorization, secret, terminalId) {
  if (typeof authorization !== 'string' || !authorization.startsWith('Bearer ')) return false;
  const presented = Buffer.from(authorization.slice('Bearer '.length));
  const expected = Buffer.from(hookTokenForTerminal(secret, terminalId));
  return presented.length === expected.length && timingSafeEqual(presented, expected);
}

/** Whether `cwd` is a place we may plant repo-local hook files: an absolute
 *  path that is NOT the user's home dir (~/.claude, ~/.codex etc. are the
 *  CLIs' USER-GLOBAL config dirs — off-limits) and not empty/relative. */
export function isRepoLocalCwd(cwd, home) {
  return !!cwd && path.isAbsolute(cwd) && !!home && path.resolve(cwd) !== path.resolve(home);
}

async function dirExists(dir) {
  try {
    return (await stat(dir)).isDirectory();
  } catch {
    return false;
  }
}

const shQuote = (s) => `'${s.replace(/'/g, `'\\''`)}'`;

/** The generic stdin→HTTP bridge all stdin-JSON CLIs share (claude, codex,
 *  cursor, grok). No stdout on purpose: every CLI accepts silent exit-0.
 *  Always exits 0 — a hook failure must never surface into the user's agent
 *  turn. */
const BRIDGE_JS = `// Generated by CURSEM IDE (agent hook injection). Do not edit.
'use strict'
const http = require('http')
const agentId = process.argv[2] || ''
let data = ''
process.stdin.setEncoding('utf8')
process.stdin.on('data', (c) => { data += c })
process.stdin.on('end', () => {
  const endpoint = process.env.${CURSEM_HOOK_ENDPOINT_ENV}
  const token = process.env.${CURSEM_HOOK_TOKEN_ENV}
  if (!endpoint || !token || !agentId) process.exit(0)
  // Cross-vendor guard. grok scans OTHER CLIs' hook files (.claude/settings
  // .local.json, .cursor/hooks.json) by default, so a grok session also spawns
  // the wrapper we injected for claude — with a grok payload. GROK_HOOK_EVENT
  // is a RESERVED var grok's hook runner injects into every hook process it
  // spawns (and strips from user-supplied env), so its presence is a
  // deterministic "grok ran me", not a heuristic: drop the post unless the
  // wrapper's baked-in agent id agrees. The grok-native wrapper still reports
  // the event, so nothing is lost.
  if (!!process.env.GROK_HOOK_EVENT !== (agentId === 'grok')) process.exit(0)
  let payload
  try { payload = JSON.parse(data) } catch { payload = { raw: data } }
  // pid: the bridge's PARENT — the agent CLI (or its sh hook-command layer),
  // never the bridge itself. The backend walks the ancestry from here to find
  // the agent process for liveness tracking.
  const body = JSON.stringify({ agentId, terminalId: process.env.${CURSEM_TERMINAL_ID_ENV} || null, pid: process.ppid, payload })
  const req = http.request(endpoint + '/hook', {
    method: 'POST',
    headers: { 'content-type': 'application/json', authorization: 'Bearer ' + token, 'content-length': Buffer.byteLength(body) },
    timeout: 3000,
  }, (res) => { res.resume(); res.on('end', () => process.exit(0)) })
  req.on('timeout', () => { req.destroy(); process.exit(0) })
  req.on('error', () => process.exit(0))
  req.end(body)
})
// Hard cap so a wedged pipe can never hold the CLI's hook slot open.
setTimeout(() => process.exit(0), 10000)
`;

// ---------------------------------------------------------------------------
// Process table snapshot (`ps` is sufficient on macOS/Linux)
// ---------------------------------------------------------------------------

/** Parse `ps -axo pid=,ppid=,comm=` output into { nameByPid, childrenByPid }.
 *  comm is the full executable path on macOS — basename it so matchers see
 *  'claude', 'grok-4.1', etc. */
export function parseProcessTable(output) {
  const nameByPid = new Map();
  const childrenByPid = new Map();
  for (const line of String(output).split('\n')) {
    const match = line.trim().match(/^(\d+)\s+(\d+)\s+(\S.*)$/);
    if (!match) continue;
    const pid = Number(match[1]);
    const ppid = Number(match[2]);
    const comm = path.basename(match[3].trim());
    nameByPid.set(pid, comm);
    const kids = childrenByPid.get(ppid);
    if (kids) kids.push(pid);
    else childrenByPid.set(ppid, [pid]);
  }
  return { nameByPid, childrenByPid };
}

async function snapshotProcessTable() {
  const { stdout } = await execFileAsync('ps', ['-axo', 'pid=,ppid=,comm='], { encoding: 'utf8', maxBuffer: 16 * 1024 * 1024 });
  return parseProcessTable(stdout);
}

function defaultIsAlive(pid) {
  try {
    process.kill(pid, 0);
    return true;
  } catch (error) {
    // EPERM = alive but not signalable by us; anything else (ESRCH) = gone.
    return error?.code === 'EPERM';
  }
}

/** Invert childrenByPid into child→parent (the walk goes up). */
function parentMap(tree) {
  const parent = new Map();
  for (const [ppid, kids] of tree.childrenByPid) {
    for (const kid of kids) parent.set(kid, ppid);
  }
  return parent;
}

// ---------------------------------------------------------------------------
// Session stamps — resumability gating (port of Cate's agentSessionStamps.ts)
// ---------------------------------------------------------------------------

/**
 * Whether this agent's session is already resumable when its session-start
 * event arrives. claude's SessionStart fires at TUI launch BEFORE any
 * transcript exists, and resuming a transcript-less id FAILS (pinned live by
 * Cate's contract suite) — so claude is only stamped from its first turn
 * event. Everyone else's first sessionId-bearing event is already tied to a
 * persisted store.
 */
const RESUMABLE_FROM_SESSION_START = {
  'claude-code': false,
  codex: true,
  // A never-used sessionStart id is resumable (--resume even ADOPTS unknown
  // ids as a fresh chat rather than failing) — pinned live.
  cursor: true,
  // grok's TUI defers SessionStart to the first prompt submit, so a session is
  // already open and on disk when the id arrives.
  grok: true,
  pi: true,
  opencode: true,
};

