// =============================================================================
// Agent hooks capability — the backend mechanism that turns the per-agent
// declarations in server/agent-hooks-spec.mjs into a live push event stream.
// Port of Cate 1.5.3 src/runtime/capabilities/agentHooks.ts + agentPresence.ts
// + src/main/ipc/agentSessionStamps.ts (MIT), adapted to CURSEM:
//
//   1. materialize a STABLE per-user hooks dir (~/.cursem/agent-hooks): the
//      stdin→HTTP bridge and per-agent bridge wrappers. Stable on purpose:
//      the bridge paths are embedded in repo-scoped hook files
//      (.claude/settings.local.json, .codex/hooks.json, …), where a per-boot
//      path would rewrite user repos every boot and re-trigger codex's
//      "modified since last trusted" hook review on every restart.
//   2. mint per-terminal hook env (endpoint + HMAC token + CURSEM_TERMINAL_ID)
//      for the TerminalOne env channel;
//   3. prepare workspace-scoped hook files at terminal create time;
//   4. ingest hook posts — NOT on its own listener: the posts ride the
//      existing cursem-server listener via /api/agent-hooks/hook (no new port
//      binds; the machine's port-allocation policy forbids them);
//   5. hook-anchored presence: every authenticated post is made BY the agent
//      (in-process plugins) or by a direct descendant of it (the stdin
//      bridge), so the post itself proves the agent exists and carries a pid
//      that leads to it. A 1 Hz `ps` scan reports liveness of the registered
//      pid; the falling edge resolves 'finished' and clears the resume stamp;
//   6. session stamps ({agentId, sessionId, cwd}) from hook events ONLY —
//      there is deliberately no store-scanning fallback: a guessed stamp
//      risks resuming the WRONG session.
//
// Per Cate 1.5.3, hooks are the ONLY detection channel: an agent that never
// speaks them (codex before its trust prompt is answered, a CLI launched
// before injection) is simply untracked — no PTY-output heuristics anywhere.
// =============================================================================

